function readCache() {
    try {
        const raw = sessionStorage.getItem(CACHE_KEY);
        if (!raw) return null;
        const parsed = JSON.parse(raw);
        if (!parsed || !Array.isArray(parsed.articles)) return null;
        if (Date.now() - parsed.timestamp > CACHE_TTL_MS) return null;
        return parsed;
    } catch (e) {
        return null;
    }
}

function writeCache(articles, lastUpdate) {
    try {
        sessionStorage.setItem(CACHE_KEY, JSON.stringify({ articles, lastUpdate, timestamp: Date.now() }));
    } catch (e) {
        // sessionStorage unavailable (e.g. private mode quota) - fail silently
    }
}

async function fetchNews(forceRefresh) {
    const refreshBtn = document.getElementById('refreshBtn');

    if (!forceRefresh) {
        const cached = readCache();
        if (cached) {
            allArticles = cached.articles;
            applyDataToUI(cached.lastUpdate);
            return;
        }
    }

    renderSkeletons(itemsPerPage);
    if (refreshBtn) refreshBtn.classList.add('loading');

    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 15000);

    try {
        const response = await fetch('fetch-all-news.php', { signal: controller.signal, cache: 'no-store' });
        clearTimeout(timeout);

        if (!response.ok) throw new Error('HTTP ' + response.status);

        const data = await response.json();

        if (data && data.success && Array.isArray(data.articles)) {
            allArticles = data.articles;
            writeCache(allArticles, data.last_update);
            applyDataToUI(data.last_update);
            if (forceRefresh) showToast('✅', 'Updated', `${allArticles.length} articles loaded`, 'g');
        } else {
            throw new Error('Invalid response shape');
        }
    } catch (error) {
        clearTimeout(timeout);
        console.error('fetchNews error:', error);

        // Fall back to stale cache if available, otherwise show error state
        const cached = readCache() || (function(){
            try {
                const raw = sessionStorage.getItem(CACHE_KEY);
                return raw ? JSON.parse(raw) : null;
            } catch(e){ return null; }
        })();

        if (cached && Array.isArray(cached.articles) && cached.articles.length) {
            allArticles = cached.articles;
            applyDataToUI(cached.lastUpdate, true);
            showToast('⚠️', 'Showing cached news', 'Could not refresh — showing last loaded articles.', 'y');
        } else {
            renderErrorState();
            showToast('⚠️', 'Error', 'Failed to load news. Please try again.', 'r');
        }
    } finally {
        if (refreshBtn) refreshBtn.classList.remove('loading');
    }
}

