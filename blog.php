function renderPagination(totalPages) {
    const container = document.getElementById('pagination');
    if (totalPages <= 1) { container.style.display = 'none'; container.innerHTML = ''; return; }
    container.style.display = 'flex';

    let html = `<button class="pg-btn" onclick="changePage(${currentPage - 1})" ${currentPage === 1 ? 'disabled' : ''} aria-label="Previous page">‹</button>`;

    const pages = [];
    const window_ = 1;
    pages.push(1);
    for (let i = currentPage - window_; i <= currentPage + window_; i++) {
        if (i > 1 && i < totalPages) pages.push(i);
    }
    if (totalPages > 1) pages.push(totalPages);
    const uniquePages = [...new Set(pages)].sort((a, b) => a - b);

    let prev = 0;
    uniquePages.forEach(p => {
        if (p - prev > 1) html += `<span class="pg-ellipsis">…</span>`;
        html += `<button class="pg-btn ${p === currentPage ? 'active' : ''}" onclick="changePage(${p})" aria-current="${p === currentPage ? 'page' : 'false'}" aria-label="Page ${p}">${p}</button>`;
        prev = p;
    });

    html += `<button class="pg-btn" onclick="changePage(${currentPage + 1})" ${currentPage === totalPages ? 'disabled' : ''} aria-label="Next page">›</button>`;
    container.innerHTML = html;
}

